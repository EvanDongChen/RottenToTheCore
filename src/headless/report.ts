// Turns the summaries written by `npm run sim` into the tables in RESULTS.md.
//
//   npm run report                 (reads results/, writes RESULTS.md)
//   npm run report -- --in results --out RESULTS.md
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Summary } from '../sim/metrics'

function flag(name: string, fallback: string) {
  const i = process.argv.indexOf(`--${name}`)
  return i >= 0 ? process.argv[i + 1] : fallback
}

const dir = flag('in', 'results')
const out = flag('out', 'RESULTS.md')

type Row = Summary & { rules?: Record<string, unknown>; firstSeed?: number; ms?: number }
const rows: Row[] = readdirSync(dir)
  .filter((f) => f.endsWith('.summary.json'))
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
  .sort((a: Row, b: Row) => `${a.crew}${a.rotten}`.localeCompare(`${b.crew}${b.rotten}`))

const pct = (n: number) => `${(n * 100).toFixed(1)}%`
const num = (n: number, d = 2) => n.toFixed(d)
const name = (r: Row) => `${r.crew} crew vs ${r.rotten} Rotten`
const table = (head: string[], body: string[][]) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...body.map((r) => `| ${r.join(' | ')} |`)].join('\n')

const ends = (r: Row, how: string) => pct(Object.entries(r.endings).filter(([k]) => k.endsWith(`:${how}`)).reduce((a, [, v]) => a + v, 0))

const sections = [
  '# Results',
  '',
  `Generated by \`npm run report\` from \`${dir}/\`. Every matchup plays the same seeds, so rows compare like with like. Default rules unless noted.`,
  '',
  '## Who wins',
  '',
  table(
    ['Matchup', 'Games', 'Crew win', 'Rotten win', 'Draw', 'By tasks', 'By ejection', 'By kills'],
    rows.map((r) => [name(r), String(r.games), pct(r.crewWinRate), pct(r.rottenWinRate), pct(r.drawRate), ends(r, 'tasks'), ends(r, 'ejection'), ends(r, 'kills')]),
  ),
  '',
  '## How well the crew reason',
  '',
  table(
    ['Matchup', 'Correct ejections', 'Wrongful ejections', 'Skipped votes', 'Ejection accuracy'],
    rows.map((r) => [name(r), String(r.correctEjections), String(r.wrongfulEjections), String(r.skips), pct(r.ejectionAccuracy)]),
  ),
  '',
  '## Pace, care and memory',
  '',
  table(
    ['Matchup', 'Game length (sim min)', 'Meetings / game', 'Kills / game', 'Kills witnessed', 'Bent memories / game', 'Wrongful ejections from bent memories', 'Contradictions / game', 'Chats / game'],
    rows.map((r) => [name(r), num(r.avgLength), num(r.meetingsPerGame), num(r.killsPerGame), pct(r.witnessedKillRate), num(r.bentMemoriesPerGame, 1), pct(r.wrongfulFromBentRate), num(r.contradictionsPerGame), num(r.chatsPerGame, 1)]),
  ),
]

const llm = rows.filter((r) => r.llm)
if (llm.length) {
  sections.push(
    '',
    '## LLM brain: cost and reliability',
    '',
    table(
      ['Matchup', 'Games', 'Calls / game', 'Tokens / game', 'Dollars / game', 'Latency / call', 'Illegal replies repaired / game', 'Hallucinated claims'],
      llm.map((r) => [name(r), String(r.games), num(r.llm!.callsPerGame, 1), String(r.llm!.tokensPerGame), `$${r.llm!.dollarsPerGame.toFixed(4)}`, `${r.llm!.avgLatencyMs} ms`, num(r.llm!.repairedPerGame), pct(r.llm!.hallucinationRate)]),
    ),
    '',
    'A hallucinated claim is a sighting an LLM fruit says it saw that is not in its own memory, checked in code against its real sightings.',
  )
}

const notes = rows.filter((r) => r.rules && Object.keys(r.rules).length)
if (notes.length) sections.push('', '## Rule overrides', '', ...notes.map((r) => `- ${name(r)}: \`${JSON.stringify(r.rules)}\``))
sections.push('')

writeFileSync(out, sections.join('\n'))
console.log(`Wrote ${out} from ${rows.length} matchup${rows.length === 1 ? '' : 's'}.`)
